'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const base=require('../js/dudu-story-engine-v1.js');
const legacy=require('../js/dudu-pilot-f-v1.js');
const model=require('../js/dudu-world-model-v2b.js');
const world=require('../js/dudu-pilot-world-v2b.js');
const engine=require('../js/dudu-story-engine-v2b.js');
const s=require('../js/dudu-pilot-f-v2b.js');
assert.deepEqual(base.validate(legacy),[],'Foundation pilot remains unchanged');
assert.deepEqual(model.validate(world),[]);
assert.deepEqual(engine.validate(s),[]);
assert.equal(s.missionId,legacy.missionId,'Preserve official seed ID');
assert.equal(s.status,'pilot_only');
assert.equal(s.released,false);
assert.equal(s.rewardsEnabled,false);
assert.equal(s.scenarioVersion,5);
assert.equal(Object.keys(world.places).length,3);
for(const p of Object.values(world.places)){
 assert.ok(fs.existsSync(path.join(root,p.background)),p.background);
 assert.ok(fs.existsSync(path.join(root,p.photo)),p.photo);
}
function play(ids,from=engine.begin(s)){
 let state=from;
 for(const id of ids){
  const out=engine.decide(s,state,id);
  assert.equal(out.accepted,true,'Choice '+id+' at '+state.sceneId+': '+out.reason);
  state=out.state;
 }
 return state;
}
const at=state=>engine.view(s,state);
const ids=state=>at(state).choices.map(c=>c.id);
const entrance=engine.begin(s);
assert.equal(entrance.sceneId,'prologue');
assert.ok(s.scenes.prologue.text.includes('Vạn Giới'));
assert.ok(!s.scenes.prologue.text.includes('túi thuốc'));
const open=play(['approach_inn_v3','help_maid_v3','ask_about_inn','stay_to_listen']);
assert.equal(open.sceneId,'hub');
assert.ok(ids(open).includes('assemble_clues'),'Suy luận phải mở tự do, không đòi 5 manh mối');
assert.ok(!ids(open).includes('store_visit_v2b'),'Cannot enter unpermitted store');
assert.ok(!ids(open).includes('report_guard_v2b'),'No verdict at hub');
assert.equal(engine.decide(s,open,'store_visit_v2b').reason,'undiscovered_action');
assert.equal(engine.decide(s,open,'report_guard_v2b').accepted,false);
const earliest=play(['assemble_clues'],open);
assert.equal(earliest.sceneId,'notes');
assert.ok(ids(earliest).includes('suspect_guard'));
assert.ok(!ids(earliest).includes('revisit_resolution'));
const premature=play(['suspect_guard'],earliest);
assert.ok(!ids(premature).includes('show_ledger_and_seal'));
assert.ok(!ids(premature).includes('only_uniform'),'Unheard witness cannot leak through choice');
assert.equal(engine.decide(s,premature,'show_ledger_and_seal').reason,'missing_story_precondition');
const wrong=play(['suspect_maid','blame_maid'],earliest);
assert.equal(wrong.endingId,'wrong');
const noIntervention=play(['approach_inn_v3','enter_inn_v2b','watch_the_room','leave_inn_v2b']);
assert.equal(noIntervention.endingId,'withdraw');
const key=play(['keeper_visit_v2b','keeper_ask_register','copy_key_log_v2b'],open);
assert.deepEqual(key.evidence,['key_log']);
assert.ok(ids(key).includes('store_visit_v2b'));
const found=play(['store_visit_v2b','check_seal_v2b','collect_seal_v2b','return_from_store_v2b'],key);
assert.deepEqual(found.evidence,['key_log','broken_seal']);
assert.ok(ids(found).includes('assemble_clues'));
const question=play(['assemble_clues','suspect_guard'],found);
assert.ok(ids(question).includes('show_ledger_and_seal'),'Independent records enable a question without fixed 5 clues');
const confronted=play(['show_ledger_and_seal'],question);
assert.equal(confronted.sceneId,'confront_guard');
assert.ok(!at(confronted).npcDetails,'No auto-quote from prior NPC state');
const admitted=play(['ask_for_full_account'],confronted);
assert.equal(admitted.sceneId,'guard_truth');
assert.ok(admitted.flags.includes('private_admission'));
assert.ok(at(admitted).npcDetails.text.includes('Tôi đã mở hòm'));
assert.ok(!ids(admitted).includes('seek_mediation_v2b'));
const unverified=play(['inspect_receipt'],admitted);
assert.ok(!unverified.evidence.includes('care_receipt'));
const stampOnly=play(['review_receipt','trust_stamp_only'],unverified);
assert.equal(stampOnly.sceneId,'receipt_doubt');
assert.ok(!stampOnly.evidence.includes('care_receipt'),'Trusting a blurry stamp alone does not verify a receipt');
const verified=play(['recheck_receipt','match_receipt_entries'],stampOnly);
assert.equal(verified.sceneId,'receipt_verified');
assert.ok(verified.evidence.includes('care_receipt'));
assert.ok(verified.flags.includes('receipt_checked'));
assert.equal(verified.evidence.length,3,'Verified route must not require all five clues');
const notes=play(['verified_back_to_notes'],verified);
assert.ok(ids(notes).includes('revisit_resolution'));
const resolution=play(['revisit_resolution'],notes);
assert.ok(!ids(resolution).includes('seek_mediation_v2b'));
assert.ok(!ids(resolution).includes('report_guard_v2b'));
const meeting=play(['invite_hearing'],resolution);
assert.equal(meeting.sceneId,'hearing');
assert.ok(!meeting.endingId,'Inviting people to sit is not a verdict');
const demand=play(['ask_for_public_confession'],meeting);
assert.equal(demand.sceneId,'hearing_silence');
assert.equal(demand.status,'playing');
assert.equal(demand.endingId,null);
assert.ok(!demand.flags.includes('public_confirmed'));
const publicProof=play(['silence_reframe','show_verified_receipt_publicly'],demand);
assert.equal(publicProof.sceneId,'hearing_proof');
assert.ok(publicProof.flags.includes('public_confirmed'));
assert.ok(!publicProof.flags.includes('public_witness_heard'));
assert.ok(!ids(publicProof).includes('move_to_joint_resolution'),'Cannot reconcile before giving the wronged person a voice');
const testimony=play(['listen_maid_again'],publicProof);
assert.equal(testimony.sceneId,'hearing_witness');
assert.equal(at(testimony).npcDetails.name,'A Liên');
assert.ok(!at(testimony).npcDetails.text.includes('Tôi đã mở hòm'),'No stale Lục Tam testimony in A Lien scene');
const ready=play(['record_witness_after_proof'],testimony);
assert.equal(ready.sceneId,'hearing_resolution');
assert.ok(ready.flags.includes('public_witness_heard'));
const reconcile=play(['seek_mediation_v2b'],ready);
assert.equal(reconcile.endingId,'reconcile');
assert.equal(reconcile.status,'success');
const formal=play(['choose_formal_record','report_guard_v2b'],resolution);
assert.equal(formal.endingId,'accountability');
assert.equal(formal.status,'success');
assert.equal(engine.decide(s,reconcile,'seek_mediation_v2b').reason,'already_finished');
assert.equal(engine.restore(s,JSON.stringify({...ready,scenarioId:'pilot-quan-dao-investigation-v4'})),null);
assert.deepEqual(engine.restore(s,engine.serialize(s,ready)),ready);
const talkedGuard=play(['guard_visit_v2b'],open);
assert.equal(at(talkedGuard).npcDetails.text,s.scenes.guard.speech,'Initial dialogue is scene-specific');
const learnedGuard=play(['guard_visit_v2b'],found);
assert.equal(at(learnedGuard).npcDetails.text,s.scenes.guard.speech,'Previous clues never replace scene dialogue');
const back=play(['guard_back'],learnedGuard);
assert.equal(at(back).npcDetails,null,'NPC dialogue must vanish outside their scene');
const lastTalk=play(['verified_more_search','guard_visit_v2b'],verified);
assert.equal(at(lastTalk).npcDetails.text,s.scenes.guard.speech,'Confession cannot persist into later unrelated scene');
const invalid=new Object();
const forged={...s,rewardsEnabled:true};
assert.ok(engine.validate(forged).includes('pilot_must_stay_locked'));
const badSpeech=JSON.parse(JSON.stringify(s));
badSpeech.scenes.hub.speech='Unattributed voice';
assert.ok(engine.validate(badSpeech).includes('invalid_scene_speech:hub'));
const invalidTravel=JSON.parse(JSON.stringify(s));
invalidTravel.scenes.prologue.choices[0].to='store';
assert.ok(engine.validate(invalidTravel).some(e=>e.includes('illegal_scene_jump')));
const ui=read('js/dudu-pilot-ui-v1.js');
assert.match(ui,/dudu:pilot-f-reasoning-v5:/);
assert.match(ui,/Sổ tay của bạn/);
assert.match(ui,/npcDetails/);
for(const html of [read('index.html'),read('dudu-pilot.html')]){
 for(const required of ['dudu-story-engine-v2b.js?v=play-v5','dudu-pilot-f-v2b.js?v=play-v5'])
  assert.ok(html.includes(required),required);
}
