const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const soul=require('../js/soul-link-v43.js');
const scope={storyId:'novel-a',chapterId:'ch-01',npcIds:['npc-a','npc-a','npc-b'],day:'2026-10-16'};
test('V43.3: only valid chapter loot grants bounded NPC-scoped fragments',()=>{
 const first=soul.earn(soul.empty(),scope);
 assert.equal(first.ok,true);assert.equal(first.granted,2);
 assert.equal(soul.count(first.state,'novel-a','npc-a'),1);
 assert.equal(soul.count(first.state,'novel-a','npc-b'),1);
 assert.equal(soul.count(first.state,'novel-b','npc-a'),0);
 assert.equal(soul.earn(first.state,scope).ok,false);
 assert.equal(soul.earn(first.state,{...scope,day:'2026-02-30'}).ok,false);
 assert.equal(soul.earn(first.state,{...scope,npcIds:['npc-a'],day:'2026-10-17',unlockedIds:['npc-a']}).ok,false);
 let s=first.state;
 for(const day of ['2026-10-17','2026-10-18','2026-10-19'])s=soul.earn(s,{...scope,day}).state;
 assert.equal(soul.count(s,'novel-a','npc-a'),3);
 assert.equal(soul.count(s,'novel-a','npc-b'),3);
 assert.equal(soul.earn(s,{...scope,day:'2026-10-20'}).ok,false);
});
test('V43.3: different chapters unlock one free mission key once per account',()=>{
 let s=soul.earn(null,scope).state;
 assert.equal(soul.claimQuest(s).ok,false);
 s=soul.earn(s,{...scope,chapterId:'ch-02'}).state;
 const a=soul.claimQuest(s);assert.equal(a.ok,true);assert.equal(a.state.keys,1);
 assert.equal(a.state.questClaimed,true);
 assert.equal(soul.claimQuest(a.state).ok,false);
 assert.equal(soul.buyKey(a.state,24).ok,false);
 const b=soul.buyKey(a.state,45);
 assert.equal(b.ok,true);assert.equal(b.coins,20);assert.equal(b.state.keys,2);
 assert.equal(soul.norm(s).keys,0,'Plans cannot mutate prior data');
});
test('V43.3: 3 fragments + one key + 20 coins unlock once, never touch other NPC or old saves',()=>{
 let s=soul.empty();
 for(let i=16;i<=18;i++)s=soul.earn(s,{...scope,day:'2026-10-'+i}).state;
 const key=soul.buyKey(s,45);
 const ok=soul.link(key.state,{storyId:'novel-a',npcId:'npc-a',coins:key.coins});
 assert.equal(ok.ok,true);assert.equal(ok.coins,0);
 assert.equal(soul.count(ok.state,'novel-a','npc-a'),0);
 assert.equal(soul.count(ok.state,'novel-a','npc-b'),3);
 assert.equal(soul.link(ok.state,{storyId:'novel-a',npcId:'npc-a',coins:100}).ok,false);
 assert.equal(soul.link(s,{storyId:'novel-a',npcId:'npc-a',coins:100,alreadyUnlocked:true}).ok,false);
 assert.equal(soul.count(s,'novel-a','npc-a'),3);
});
test('V43.3: invalid or hostile save inputs remain inert',()=>{
 assert.deepEqual(soul.norm({version:999,keys:99}),soul.empty());
 assert.equal(soul.earn({}, {storyId:'a',chapterId:'ch',npcIds:['npc'],day:'BAD'}).ok,false);
 assert.equal(soul.buyKey({},Number.POSITIVE_INFINITY).ok,false);
 assert.equal(soul.link({}, {storyId:'a',npcId:'b',coins:NaN}).ok,false);
 assert.equal(soul.count(null,'','b'),0);
 const unsafe={version:1,keys:999,fragments:JSON.parse('{"__proto__":3,"novel-a::npc-a":4}')};
 const normalized=soul.norm(unsafe);
 assert.equal(Object.getPrototypeOf(normalized.fragments),Object.prototype);
 assert.equal(soul.count(normalized,'novel-a','npc-a'),3);
 assert.ok(normalized.keys<=20);
});
