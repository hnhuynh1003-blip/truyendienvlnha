// Publish reproducible static validation only; never bundle server writers.
import {build} from 'esbuild';
import fs from 'node:fs';
const root=new URL('../../',import.meta.url);
const result=await build({entryPoints:[new URL('js/vangioi-creator-validation-entry.mjs',root).pathname],
 bundle:true,write:false,format:'iife',globalName:'DuduWorldValidation',platform:'browser',target:'es2020',
 minify:true,legalComments:'none',charset:'utf8'});
const contents='// Generated by cloudflare/scripts/build-vangioi-creator.mjs. Do not edit.\n'+result.outputFiles[0].text;
const file=new URL('js/vangioi-creator-validation.js',root);
if(process.argv.includes('--check')){
 if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==contents)throw Error('Regenerate creator validation bundle');
}else fs.writeFileSync(file,contents);
