// Build-time only: never compile user schemas or call code generation in Workers.
import fs from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root=new URL('../../',import.meta.url);
const source=JSON.parse(fs.readFileSync(new URL('contracts/vangioi/source-v0.1/world.schema.json',root),'utf8'));
const schema=structuredClone(source),p=schema.properties;
for(const key of ['worldId','worldRank','status','author','rankException'])delete p[key];
schema.$id='https://dudu.studio/schemas/vangioi/world-content-1.json';
schema.title='Vangioi authoring content for review';
schema.description='Content only. Ownership, permissions, workflow and official rank are server-owned.';
schema.$defs.nonempty.pattern='\\S';
p.schemaVersion={const:'world-content-1'};
p.genreId.enum=['ancient','modern','era','future','cultivation','apocalypse'];
p.requestedWorldRank={enum:['F','E','D','C','B','A','S']};
p.entry={type:'object',additionalProperties:false,required:['entrySceneId'],
 properties:{entrySceneId:{$ref:'#/$defs/id'}}};
schema.$defs.hash={type:'string',pattern:'^[a-f0-9]{64}$'};
p.storySource={type:'object',additionalProperties:false,
 required:['kind','storyId','storyVersion','contentHash'],properties:{
  kind:{enum:['original','library','manuscript']},storyId:{type:'string',minLength:1,maxLength:160},
  storyVersion:{type:'string',minLength:1,maxLength:100},contentHash:{$ref:'#/$defs/hash'}}};
const asset=schema.$defs.asset.properties;
schema.$defs.asset={type:'object',additionalProperties:false,
 required:['assetId','assetVersion','contentHash','kind','altText'],properties:{
  assetId:{$ref:'#/$defs/id'},assetVersion:{type:'string',minLength:1,maxLength:100},
  contentHash:{$ref:'#/$defs/hash'},kind:asset.kind,altText:{$ref:'#/$defs/nonempty'},focalPoint:asset.focalPoint}};
schema.required=[...new Set([...schema.required.filter(k=>Object.hasOwn(p,k)),'requestedWorldRank','storySource'])];
function visit(v,fn){
 if(v&&typeof v==='object'){
  if(!Array.isArray(v))fn(v);
  Object.values(v).forEach(x=>visit(x,fn));
 }
}
visit(schema,v=>{if(v.type==='integer')v.maximum=Math.min(v.maximum??Number.MAX_SAFE_INTEGER,Number.MAX_SAFE_INTEGER);});
const draft=structuredClone(schema);
draft.$id='https://dudu.studio/schemas/vangioi/world-content-1-draft.json';
draft.title='Vangioi incomplete authoring draft';
visit(draft,v=>{for(const key of ['required','minItems','minLength'])delete v[key];});
delete draft.$defs.nonempty.pattern;
const ajv=new Ajv2020({strict:true,strictTuples:false,allErrors:true,inlineRefs:false,code:{source:true,optimize:true}});
ajv.addSchema(schema).addSchema(draft);
const generated='// Generated by scripts/build-vangioi-validator.mjs. Do not edit.\n'+
 standaloneCode(ajv,{validateSubmit:schema.$id,validateDraft:draft.$id})+'\n';
const outputs=[
 ['contracts/vangioi/world-content-1.schema.json',JSON.stringify(schema,null,2)+'\n'],
 ['contracts/vangioi/world-content-1-draft.schema.json',JSON.stringify(draft,null,2)+'\n'],
 ['cloudflare/src/generated/vangioi-content-validators.cjs',generated]
];
for(const [path,contents] of outputs){
 const file=new URL(path,root);
 if(process.argv.includes('--check')){
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==contents)throw Error('Regenerate '+path);
 }else{fs.mkdirSync(new URL('.',file),{recursive:true});fs.writeFileSync(file,contents);}
}
